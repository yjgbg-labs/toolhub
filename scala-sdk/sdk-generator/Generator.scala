package sprout.sdk.generator

import io.circe.Json
import sprout.sdk.*
import sprout.sdk.Catalog.*
import scala.collection.mutable

/** Pure source generation. No filesystem, JVM, JS host, HTTP or business dependency. */
object Generator:
  val header = "// Generated by sprout-scala-sdk. Do not edit.\n"
  def generate(document: Json, packageName: String): Map[String, String] = generate(new Catalog(document), packageName)
  def generate(catalog: Catalog, packageName: String): Map[String, String] = new Generation(catalog, packageName).files

  private final case class Shape(tpe: String, codec: String)
  private def q(value: String): String = Json.fromString(value).noSpaces.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
  private def id(value: String): String =
    require(value.nonEmpty && !value.exists(c => c == '`' || c == '\r' || c == '\n' || c == 0), s"Invalid Scala identifier: ${q(value)}")
    s"`$value`"
  private def typeName(value: String): String =
    val name = value.split("[^A-Za-z0-9]+").filter(_.nonEmpty).map(part => part.head.toUpper.toString + part.tail).mkString
    if name.headOption.exists(_.isLetter) then name else "Model" + name
  private def indent(value: String, spaces: Int): String = value.split("\n", -1).map(" " * spaces + _).mkString("\n")

  private final class Generation(catalog: Catalog, packageName: String):
    require(packageName.matches("[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)*"), "Invalid Scala package")
    private val definitions = mutable.ArrayBuffer.empty[String]
    private val names = mutable.Set("Client", "Calls", "JsonCodec", "Json", "Optional", "Call", "HttpRequest", "HttpResponse", "Wire", "Executor", "ClientError", "Vector", "Map", "Option", "String", "Int", "Long", "BigInt", "BigDecimal", "Double", "Boolean", "Unit")
    private val components = catalog.document.hcursor.downField("components").downField("schemas").focus.fold(Vector.empty[(String, Json)])(obj(_, "components.schemas").toVector.sortBy(_._1))
    private def reserve(preferred: String): String =
      val base = typeName(preferred)
      var name = base
      var index = 2
      while names(name) do
        name = s"$base$index"
        index += 1
      names += name
      name
    private def reference(key: String): String = "#/components/schemas/" + key.replace("~", "~0").replace("/", "~1")
    private val refs = components.map { (key, _) =>
      val name = reserve(key.split('.').last.replaceAll("_[a-f0-9]{16}$", ""))
      reference(key) -> Shape(name, s"$name.codec")
    }.toMap

    private def alias(result: Shape, named: Option[String]): Shape = named match
      case None => result
      case Some(name) =>
        definitions += s"type $name = ${result.tpe}\nobject $name:\n  lazy val codec: JsonCodec[$name] = ${result.codec}"
        Shape(name, s"$name.codec")

    private def shape(raw: Json, hint: String, named: Option[String] = None): Shape =
      val fields = obj(raw, hint)
      field(raw, "$ref") match
        case Some(ref) =>
          require(fields.keys.forall(Set("$ref", "description", "default", "title")), s"$hint: schema reference siblings are not supported")
          val result = refs.getOrElse(ref.asString.getOrElse(""), throw new IllegalArgumentException(s"$hint: unsupported schema reference $ref"))
          alias(result, named)
        case None =>
          Vector("allOf", "not", "if", "then", "else", "patternProperties", "prefixItems", "$dynamicRef", "unevaluatedProperties").foreach { key =>
            require(!fields.contains(key), s"$hint: unsupported JSON Schema keyword $key")
          }
          val kinds = types(raw)
          if kinds.contains("null") && kinds.size > 1 then
            require(kinds.size == 2, s"$hint: unsupported multi-type schema")
            val inner = shape(raw.mapObject(_.add("type", Json.fromString(kinds.find(_ != "null").get))), s"${hint}Value")
            alias(Shape(s"Option[${inner.tpe}]", s"JsonCodec.nullable(${inner.codec})"), named)
          else if fields.contains("enum") then
            val values = array(raw, "enum").map(_.asString.getOrElse(throw new IllegalArgumentException(s"$hint: only string enums are supported")))
            require(values.nonEmpty && values.distinct.size == values.size, s"$hint: empty or duplicate enum")
            val name = named.getOrElse(reserve(hint))
            val cases = values.indices.map(i => s"  case Value${i + 1}").mkString("\n")
            val encode = values.zipWithIndex.map((value, i) => s"      case $name.Value${i + 1} => ${q(value)}").mkString("\n")
            val decode = values.zipWithIndex.map((value, i) => s"      case ${q(value)} => Right($name.Value${i + 1})").mkString("\n")
            definitions += s"""enum $name:
$cases
object $name:
  lazy val codec: JsonCodec[$name] = JsonCodec(
    value => Json.fromString(value match
$encode
    ),
    json => JsonCodec.string.read(json).flatMap {
$decode
      case other => Left("Unknown $name: " + other)
    }
  )"""
            Shape(name, s"$name.codec")
          else if fields.contains("oneOf") || fields.contains("anyOf") then
            val exclusive = fields.contains("oneOf")
            val choices = array(raw, if exclusive then "oneOf" else "anyOf")
            require(choices.nonEmpty, s"$hint: empty union")
            val name = named.getOrElse(reserve(hint))
            val variants = choices.zipWithIndex.map((value, i) => shape(value, s"${name}Variant${i + 1}"))
            val cases = variants.zipWithIndex.map((s, i) => s"  case Variant${i + 1}(value: ${s.tpe})").mkString("\n")
            val encode = variants.zipWithIndex.map((s, i) => s"      case $name.Variant${i + 1}(value) => ${s.codec}.write(value)").mkString("\n")
            val decode = variants.zipWithIndex.map((s, i) => s"        ${s.codec}.read(json).map($name.Variant${i + 1}.apply)").mkString(",\n")
            val select = if exclusive then "if matches.size == 1 then Right(matches.head) else Left(\"Expected exactly one matching union variant\")" else "matches.headOption.toRight(\"No matching union variant\")"
            definitions += s"""enum $name:
$cases
object $name:
  lazy val codec: JsonCodec[$name] = JsonCodec(
    {
$encode
    },
    json => {
      val matches: Vector[$name] = Vector(
$decode
      ).flatMap(_.toOption)
      $select
    }
  )"""
            Shape(name, s"$name.codec")
          else if fields.contains("const") then
            val value = fields("const").flatMap(_.asString).getOrElse(throw new IllegalArgumentException(s"$hint: only string const is supported"))
            alias(Shape("String", s"JsonCodec[String](Json.fromString, json => JsonCodec.string.read(json).flatMap(value => Either.cond(value == ${q(value)}, value, \"Unexpected constant\")))"), named)
          else
            val primitive = optionalText(raw, "type") match
              case "string" => Some(Shape("String", "JsonCodec.string"))
              case "boolean" => Some(Shape("Boolean", "JsonCodec.boolean"))
              case "integer" => Some(optionalText(raw, "format") match
                case "int32" => Shape("Int", "JsonCodec.int")
                case "int64" => Shape("Long", "JsonCodec.long")
                case _ => Shape("BigInt", "JsonCodec.bigInt"))
              case "number" => Some(if Set("double", "float")(optionalText(raw, "format")) then Shape("Double", "JsonCodec.double") else Shape("BigDecimal", "JsonCodec.decimal"))
              case _ => None
            primitive match
              case Some(result) => alias(result, named)
              case None if kinds.contains("array") =>
                val inner = shape(fields("items").getOrElse(Json.Null), s"${hint}Item")
                alias(Shape(s"Vector[${inner.tpe}]", s"JsonCodec.vector(${inner.codec})"), named)
              case None if kinds.contains("object") || fields.contains("properties") =>
                val additional = fields("additionalProperties")
                if !fields.contains("properties") && !additional.contains(Json.False) then
                  val value = additional.filter(_ != Json.True).fold(Shape("Json", "JsonCodec.json"))(shape(_, s"${hint}Value"))
                  alias(Shape(s"Map[String, ${value.tpe}]", s"JsonCodec.dictionary(${value.codec})"), named)
                else
                  require(!additional.exists(_.isObject), s"$hint: mixed fixed/dictionary object is not supported")
                  val name = named.getOrElse(reserve(hint))
                  val properties = obj(fields("properties").getOrElse(Json.obj()), s"$hint.properties")
                  val required = array(raw, "required").map(_.asString.get).toSet
                  require(required.forall(properties.contains), s"$hint: undeclared required property")
                  val members = properties.toVector.map((key, value) => (key, shape(value, name + typeName(key)), required(key)))
                  val parameters = members.map((key, s, req) => s"${id(key)}: ${if req then s.tpe else s"Optional[${s.tpe}] = Optional.Missing"}").mkString(", ")
                  val encoded = members.map { (key, s, req) =>
                    if req then s"Vector(${q(key)} -> ${s.codec}.write(value.${id(key)}))" else s"JsonCodec.optionalField(${q(key)}, value.${id(key)}, ${s.codec})"
                  }.mkString(" ++ ") match
                    case "" => "Vector.empty"
                    case value => value
                  val decoded = if members.isEmpty then s"Either.cond(json.isObject, $name(), \"Expected object\")" else
                    "for\n" + members.zipWithIndex.map { case ((key, s, req), i) =>
                      s"      field$i <- JsonCodec.${if req then "field" else "optional"}(json, ${q(key)}, ${s.codec})"
                    }.mkString("\n") + s"\n    yield $name(${members.indices.map(i => s"field$i").mkString(", ")})"
                  definitions += s"""final case class $name($parameters)
object $name:
  lazy val codec: JsonCodec[$name] = JsonCodec(
    value => Json.fromFields($encoded),
    json => $decoded
  )"""
                  Shape(name, s"$name.codec")
              case None if fields.keys.forall(Set("description", "title", "default")) => alias(Shape("Json", "JsonCodec.json"), named)
              case _ => throw new IllegalArgumentException(s"$hint: unsupported schema ${raw.noSpaces}")

    private final case class Argument(name: String, shape: Shape, required: Boolean, parameter: Option[Parameter] = None)
    private final case class Variant(status: Int, media: Option[String], shape: Shape, decode: String, name: String)
    private final case class Method(operation: Operation, signature: String, result: String, expression: String, args: String)
    private def method(operation: Operation): Method =
      val prefix = typeName(operation.id)
      val parameters = operation.parameters.map { param =>
        val name = if operation.parameters.count(_.name == param.name) > 1 || param.name == "body" then s"${param.location}_${param.name}" else param.name
        Argument(name, shape(param.schema, prefix + typeName(name)), param.required, Some(param))
      }
      val body = operation.body.map(body => Argument("body", shape(body.schema, s"${prefix}Body"), body.required))
      val args = parameters ++ body
      require(args.map(_.name).distinct.size == args.size, s"${operation.id}: argument name collision")
      val path = parameters.filter(_.parameter.exists(_.location == "path")).foldLeft(q(operation.path)) { (path, arg) =>
        path + s".replace(${q("{" + arg.parameter.get.name + "}")}, Wire.encode(Wire.scalar(${arg.shape.codec}.write(${id(arg.name)}))))"
      }
      def pairs(location: String): String =
        val parts = parameters.filter(_.parameter.exists(_.location == location)).map { arg =>
          val param = arg.parameter.get
          def encode(value: String) = s"Wire.parameters(${q(param.name)}, ${arg.shape.codec}.write($value), ${param.explode})"
          if arg.required then encode(id(arg.name)) else s"${id(arg.name)}.toOption.toVector.flatMap(value => ${encode("value")})"
        }
        if parts.isEmpty then "Vector.empty" else parts.mkString(" ++ ")
      val contentType = body.fold("Vector.empty") { arg =>
        if arg.required then "Vector(\"Content-Type\" -> \"application/json\")" else "`body`.toOption.toVector.map(_ => \"Content-Type\" -> \"application/json\")"
      }
      val headers = s"${pairs("header")} ++ $contentType ++ { val cookies: Vector[(String, String)] = ${pairs("cookie")}; if cookies.isEmpty then Vector.empty else Vector(\"Cookie\" -> cookies.map((k, v) => Wire.encode(k) + \"=\" + Wire.encode(v)).mkString(\"; \")) }"
      val payload = body.fold("None")(arg => if arg.required then s"Some(${arg.shape.codec}.write(`body`).noSpaces)" else s"`body`.toOption.map(value => ${arg.shape.codec}.write(value).noSpaces)")
      val variants = operation.responses.filter(_.status.startsWith("2")).flatMap { response =>
        require(response.status.matches("2[0-9]{2}"), s"${operation.id}: success status ranges are unsupported")
        response.bodies.map { body =>
          body.mediaType match
            case None => Variant(response.status.toInt, None, Shape("Unit", ""), "Right(())", "Status" + response.status)
            case Some(media) =>
              require(media == "text/plain" || media == "application/json" || media.endsWith("+json"), s"${operation.id}: unsupported response media $media")
              val s = if media == "text/plain" then Shape("String", "JsonCodec.string") else shape(body.schema, s"${prefix}Response${response.status}")
              Variant(response.status.toInt, Some(media), s, if media == "text/plain" then "Right(response.body)" else s"Wire.json(response, ${s.codec})", s"Status${response.status}${typeName(media)}")
        }
      }
      require(variants.nonEmpty, s"${operation.id}: no declared success response")
      val result = if variants.size == 1 then variants.head.shape.tpe else reserve(s"${prefix}Result")
      if variants.size > 1 then definitions += s"enum $result:\n" + variants.map(v => s"  case ${v.name}(value: ${v.shape.tpe})").mkString("\n")
      val branches = variants.map { v =>
        val guard = v.media.fold("")(media => s" if response.mediaType.contains(${q(media)})")
        val mapped = if variants.size > 1 then s".map($result.${v.name}.apply)" else ""
        s"case ${v.status}$guard => ${v.decode}$mapped"
      }.mkString("\n")
      val expression = s"""Call[$result](
  HttpRequest(${q(operation.method)}, $path, query = ${pairs("query")}, headers = $headers, body = $payload),
  response => response.status match
${indent(branches, 4)}
    case _ => Wire.unexpected(response)
)"""
      Method(operation, args.map(arg => s"${id(arg.name)}: ${if arg.required then arg.shape.tpe else s"Optional[${arg.shape.tpe}] = Optional.Missing"}").mkString(", "), result, expression, args.map(arg => id(arg.name)).mkString(", "))

    def files: Map[String, String] =
      components.foreach((key, value) => shape(value, key, Some(refs(reference(key)).tpe)))
      val methods = catalog.operations.map(method)
      final class Node:
        val children = mutable.LinkedHashMap.empty[String, Node]
        var method: Option[Method] = None
      val root = new Node
      methods.foreach { method =>
        var node = root
        method.operation.segments.foreach { segment =>
          require(node.method.isEmpty, s"Command is also a namespace: ${method.operation.id}")
          node = node.children.getOrElseUpdate(segment, new Node)
        }
        require(node.children.isEmpty, s"Command is also a namespace: ${method.operation.id}")
        node.method = Some(method)
      }
      def render(node: Node, bound: Boolean, depth: Int = 1): String = node.children.toVector.map { (name, child) =>
        val pad = "  " * depth
        child.method match
          case None => s"${pad}object ${id(name)}:\n${render(child, bound, depth + 1)}"
          case Some(method) =>
            val description = method.operation.description.replace("*/", "* /").replaceAll("[\r\n]", " ")
            val comment = if description.isEmpty then "" else s"$pad/** $description */\n"
            val expression = if bound then s"executor.execute(Calls.${method.operation.segments.map(id).mkString(".")}(${method.args}))" else method.expression
            s"$comment${pad}def ${id(name)}(${method.signature}): ${if bound then "F" else "Call"}[${method.result}] =\n${indent(expression, (depth + 1) * 2)}"
      }.mkString("\n\n")
      val prelude = s"${Generator.header}package ${packageName.split('.').map(id).mkString(".")}\n\nimport sprout.sdk.*\nimport io.circe.Json\n\n"
      Map(
        "Models.scala" -> (prelude + definitions.mkString("\n\n") + "\n"),
        "Calls.scala" -> (prelude + "object Calls:\n" + (if root.children.isEmpty then "  ()" else render(root, false)) + "\n"),
        "Client.scala" -> (prelude + "final class Client[F[_]](executor: Executor[F]):\n" + (if root.children.isEmpty then "  ()" else render(root, true)) + "\n")
      )
