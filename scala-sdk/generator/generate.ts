// Host bridge to the cross-published Scala generator, built by generator-build.
const moduleUrl = new URL("../dist/generator.mjs", import.meta.url).href;
const runtime = await import(moduleUrl) as { generate(schema: string, packageName: string): string };
export const generatedHeader = "// Generated by sprout-scala-sdk. Do not edit.\n";
export function generateText(schema: string, packageName: string): Record<string, string> {
  return JSON.parse(runtime.generate(schema, packageName));
}
export function generate(document: unknown, packageName: string): Record<string, string> {
  return generateText(JSON.stringify(document), packageName);
}
