type Schema = Record<string, any>;
type Shape = { type: string; codec: string };
const methods = new Set(["get", "post", "put", "patch", "delete", "head", "options"]);
const header = "// Generated by sprout-scala-sdk. Do not edit.\n";
const q = (value: string) => JSON.stringify(value).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
const id = (value: string) => {
  if (!value || /[`\r\n\u0000]/.test(value)) throw new Error(`Invalid Scala identifier: ${JSON.stringify(value)}`);
  return `\`${value}\``;
};
const typeName = (value: string) => {
  const name = value.replace(/[^A-Za-z0-9]+/g, " ").split(" ").filter(Boolean).map(v => v[0]!.toUpperCase() + v.slice(1)).join("");
  return /^[A-Za-z]/.test(name) ? name : `Model${name}`;
};
function object(value: unknown, where: string): Schema {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error(`${where}: expected object`);
  return value as Schema;
}

export function generate(document: unknown, packageName: string): Record<string, string> {
  if (!/^[A-Za-z_][\w]*(\.[A-Za-z_][\w]*)*$/.test(packageName)) throw new Error("Invalid Scala package");
  const doc = object(document, "OpenAPI");
  if (!/^3\.1\./.test(doc.openapi)) throw new Error("Expected OpenAPI 3.1");
  const definitions: string[] = [];
  const names = new Set(["Client", "Calls", "JsonCodec", "Json", "Optional", "Call", "HttpRequest", "HttpResponse", "Wire", "Executor", "ClientError", "Vector", "Map", "Option", "String", "Int", "Long", "BigInt", "BigDecimal", "Double", "Boolean", "Unit"]);
  const components = object(doc.components?.schemas ?? {}, "components.schemas");
  const refs = new Map<string, Shape>();
  const reserve = (preferred: string) => {
    const base = typeName(preferred);
    let name = base;
    for (let i = 2; names.has(name); i++) name = `${base}${i}`;
    names.add(name);
    return name;
  };
  const pointer = (ref: string): Schema => {
    if (!ref.startsWith("#/")) throw new Error(`Only document-local references are supported: ${ref}`);
    let value: any = doc;
    for (const key of ref.slice(2).split("/").map(v => decodeURIComponent(v).replace(/~1/g, "/").replace(/~0/g, "~"))) {
      if (!value || !Object.hasOwn(value, key)) throw new Error(`Unresolved reference: ${ref}`);
      value = value[key];
    }
    return object(value, ref);
  };
  const resolve = (raw: unknown, seen = new Set<string>()): Schema => {
    const entry = object(raw, "OpenAPI entry");
    if (!entry.$ref) return entry;
    if (seen.has(entry.$ref)) throw new Error(`Cyclic non-schema reference: ${entry.$ref}`);
    seen.add(entry.$ref);
    const { $ref, ...rest } = entry;
    return { ...resolve(pointer($ref), seen), ...rest };
  };

  for (const key of Object.keys(components).sort()) {
    const short = key.split(".").at(-1)!.replace(/_[a-f0-9]{16}$/, "");
    const name = reserve(short);
    refs.set(`#/components/schemas/${key.replace(/~/g, "~0").replace(/\//g, "~1")}`, { type: name, codec: `${name}.codec` });
  }

  function shape(raw: unknown, hint: string, named?: string): Shape {
    const schema = object(raw, hint);
    if (schema.$ref) {
      if (Object.keys(schema).some(key => !["$ref", "description", "default", "title"].includes(key))) {
        throw new Error(`${hint}: schema reference siblings are not supported`);
      }
      const result = refs.get(schema.$ref);
      if (!result) throw new Error(`${hint}: unsupported schema reference ${schema.$ref}`);
      if (named) definitions.push(`type ${named} = ${result.type}\nobject ${named}:\n  lazy val codec: JsonCodec[${named}] = ${result.codec}`);
      return named ? { type: named, codec: `${named}.codec` } : result;
    }
    for (const key of ["allOf", "not", "if", "then", "else", "patternProperties", "prefixItems", "$dynamicRef", "unevaluatedProperties"]) {
      if (schema[key] !== undefined) throw new Error(`${hint}: unsupported JSON Schema keyword ${key}`);
    }
    const types: string[] = Array.isArray(schema.type) ? schema.type : [schema.type];
    if (types.includes("null") && types.length > 1) {
      if (types.length !== 2) throw new Error(`${hint}: unsupported multi-type schema`);
      const inner = shape({ ...schema, type: types.find(t => t !== "null") }, `${hint}Value`);
      return alias({ type: `Option[${inner.type}]`, codec: `JsonCodec.nullable(${inner.codec})` }, named);
    }
    if (schema.enum) {
      if (!Array.isArray(schema.enum) || !schema.enum.length || schema.enum.some((value: unknown) => typeof value !== "string")) throw new Error(`${hint}: only string enums are supported`);
      if (new Set(schema.enum).size !== schema.enum.length) throw new Error(`${hint}: duplicate enum value`);
      const name = named ?? reserve(hint);
      const cases = schema.enum.map((value: string, i: number) => `  case Value${i + 1}`).join("\n");
      definitions.push(`enum ${name}:\n${cases}\nobject ${name}:\n  lazy val codec: JsonCodec[${name}] = JsonCodec(\n    value => Json.fromString(value match\n${schema.enum.map((v: string, i: number) => `      case ${name}.Value${i + 1} => ${q(v)}`).join("\n")}\n    ),\n    json => JsonCodec.string.read(json).flatMap {\n${schema.enum.map((v: string, i: number) => `      case ${q(v)} => Right(${name}.Value${i + 1})`).join("\n")}\n      case other => Left("Unknown ${name}: " + other)\n    }\n  )`);
      return { type: name, codec: `${name}.codec` };
    }
    if (schema.oneOf || schema.anyOf) {
      const choices = schema.oneOf ?? schema.anyOf;
      if (!Array.isArray(choices) || !choices.length) throw new Error(`${hint}: empty union`);
      const name = named ?? reserve(hint);
      const variants = choices.map((s: unknown, i: number) => shape(s, `${name}Variant${i + 1}`));
      definitions.push(`enum ${name}:\n${variants.map((s, i) => `  case Variant${i + 1}(value: ${s.type})`).join("\n")}\nobject ${name}:\n  lazy val codec: JsonCodec[${name}] = JsonCodec(\n    {\n${variants.map((s, i) => `      case ${name}.Variant${i + 1}(value) => ${s.codec}.write(value)`).join("\n")}\n    },\n    json => {\n      val matches: Vector[${name}] = Vector(\n${variants.map((s, i) => `        ${s.codec}.read(json).map(${name}.Variant${i + 1}.apply)`).join(",\n")}\n      ).flatMap(_.toOption)\n      ${schema.oneOf ? 'if matches.size == 1 then Right(matches.head) else Left("Expected exactly one matching union variant")' : 'matches.headOption.toRight("No matching union variant")'}\n    }\n  )`);
      return { type: name, codec: `${name}.codec` };
    }
    if (schema.const !== undefined) {
      const value = schema.const;
      if (typeof value !== "string") throw new Error(`${hint}: only string const is supported`);
      return alias({ type: "String", codec: `JsonCodec[String](Json.fromString, json => JsonCodec.string.read(json).flatMap(value => Either.cond(value == ${q(value)}, value, "Unexpected constant")))` }, named);
    }
    const primitive: Record<string, Shape> = {
      string: { type: "String", codec: "JsonCodec.string" },
      boolean: { type: "Boolean", codec: "JsonCodec.boolean" },
      integer: schema.format === "int32" ? { type: "Int", codec: "JsonCodec.int" } : schema.format === "int64" ? { type: "Long", codec: "JsonCodec.long" } : { type: "BigInt", codec: "JsonCodec.bigInt" },
      number: ["double", "float"].includes(schema.format) ? { type: "Double", codec: "JsonCodec.double" } : { type: "BigDecimal", codec: "JsonCodec.decimal" },
    };
    if (primitive[schema.type]) return alias(primitive[schema.type]!, named);
    if (schema.type === "array") {
      const inner = shape(schema.items, `${hint}Item`);
      return alias({ type: `Vector[${inner.type}]`, codec: `JsonCodec.vector(${inner.codec})` }, named);
    }
    if (schema.type === "object" || schema.properties) {
      if (!schema.properties && schema.additionalProperties !== false) {
        const value = schema.additionalProperties && schema.additionalProperties !== true ? shape(schema.additionalProperties, `${hint}Value`) : { type: "Json", codec: "JsonCodec.json" };
        return alias({ type: `Map[String, ${value.type}]`, codec: `JsonCodec.dictionary(${value.codec})` }, named);
      }
      if (typeof schema.additionalProperties === "object") throw new Error(`${hint}: mixed fixed/dictionary object is not supported`);
      const name = named ?? reserve(hint);
      const properties = object(schema.properties ?? {}, `${hint}.properties`);
      const required = new Set<string>(schema.required ?? []);
      for (const key of required) if (!Object.hasOwn(properties, key)) throw new Error(`${hint}: required property ${key} is undeclared`);
      const fields = Object.entries(properties).map(([key, value]) => ({ key, ...shape(value, `${name}${typeName(key)}`), required: required.has(key) }));
      const parameters = fields.map(f => `${id(f.key)}: ${f.required ? f.type : `Optional[${f.type}] = Optional.Missing`}`).join(", ");
      const encoded = fields.map(f => f.required ? `Vector(${q(f.key)} -> ${f.codec}.write(value.${id(f.key)}))` : `JsonCodec.optionalField(${q(f.key)}, value.${id(f.key)}, ${f.codec})`).join(" ++ ") || "Vector.empty";
      const decoded = fields.length ? `for\n${fields.map((f, i) => `      field${i} <- JsonCodec.${f.required ? "field" : "optional"}(json, ${q(f.key)}, ${f.codec})`).join("\n")}\n    yield ${name}(${fields.map((_, i) => `field${i}`).join(", ")})` : `Either.cond(json.isObject, ${name}(), "Expected object")`;
      definitions.push(`final case class ${name}(${parameters})\nobject ${name}:\n  lazy val codec: JsonCodec[${name}] = JsonCodec(\n    value => Json.fromFields(${encoded}),\n    json => ${decoded}\n  )`);
      return { type: name, codec: `${name}.codec` };
    }
    if (Object.keys(schema).every(key => ["description", "title", "default"].includes(key))) return alias({ type: "Json", codec: "JsonCodec.json" }, named);
    throw new Error(`${hint}: unsupported schema ${JSON.stringify(schema)}`);
  }
  function alias(result: Shape, named?: string): Shape {
    if (!named) return result;
    definitions.push(`type ${named} = ${result.type}\nobject ${named}:\n  lazy val codec: JsonCodec[${named}] = ${result.codec}`);
    return { type: named, codec: `${named}.codec` };
  }
  for (const key of Object.keys(components).sort()) {
    const ref = `#/components/schemas/${key.replace(/~/g, "~0").replace(/\//g, "~1")}`;
    shape(components[key], key, refs.get(ref)!.type);
  }

  interface Operation { segments: string[]; signature: string; result: string; expression: string; args: string; description: string }
  const operations: Operation[] = [];
  const operationIds = new Set<string>();
  for (const [path, rawItem] of Object.entries(object(doc.paths, "paths"))) {
    const item = resolve(rawItem);
    if (!path.startsWith("/") || /[?#]/.test(path)) throw new Error(`Invalid HTTP path: ${path}`);
    for (const [method, rawOp] of Object.entries(item)) {
      if (!methods.has(method)) continue;
      const op = object(rawOp, `${method} ${path}`);
      if (!/^[A-Za-z][A-Za-z0-9_-]*(\.[A-Za-z][A-Za-z0-9_-]*)*$/.test(op.operationId)) throw new Error(`Invalid operationId: ${op.operationId}`);
      if (operationIds.has(op.operationId)) throw new Error(`Duplicate operationId: ${op.operationId}`);
      operationIds.add(op.operationId);
      const prefix = typeName(op.operationId);
      const parameters = new Map<string, Schema>();
      for (const p of [...(item.parameters ?? []), ...(op.parameters ?? [])]) {
        const param = resolve(p);
        if (!["path", "query", "header", "cookie"].includes(param.in) || typeof param.name !== "string") throw new Error(`${op.operationId}: invalid parameter`);
        const expected = ["path", "header"].includes(param.in) ? "simple" : "form";
        if (param.style && param.style !== expected || param.allowReserved) throw new Error(`${op.operationId}: unsupported parameter serialization`);
        parameters.set(`${param.in}:${param.in === "header" ? param.name.toLowerCase() : param.name}`, param);
      }
      const params = [...parameters.values()];
      const args: { name: string; shape: Shape; required: boolean; param?: Schema }[] = [];
      for (const param of params) {
        const schema = resolve(param.schema);
        const baseType = Array.isArray(schema.type) ? schema.type.find((t: string) => t !== "null") : schema.type;
        if (!["string", "number", "integer", "boolean", "array"].includes(baseType) || baseType === "array" && (param.in !== "query" || !["string", "number", "integer", "boolean"].includes(resolve(schema.items).type))) throw new Error(`${op.operationId}: unsupported parameter shape`);
        const duplicate = params.filter(p => p.name === param.name).length > 1;
        const name = duplicate || param.name === "body" ? `${param.in}_${param.name}` : param.name;
        args.push({ name, shape: shape(param.schema, `${prefix}${typeName(name)}`), required: param.required === true || param.in === "path", param });
      }
      let body: typeof args[number] | undefined;
      if (op.requestBody) {
        if (["get", "head"].includes(method)) throw new Error(`${op.operationId}: GET/HEAD body is unsupported`);
        const request = resolve(op.requestBody);
        if (Object.keys(request.content ?? {}).join() !== "application/json") throw new Error(`${op.operationId}: only JSON request bodies are supported`);
        body = { name: "body", shape: shape(request.content["application/json"].schema, `${prefix}Body`), required: request.required === true };
        args.push(body);
      }
      if (new Set(args.map(a => a.name)).size !== args.length) throw new Error(`${op.operationId}: argument name collision`);
      let pathExpr = q(path);
      for (const placeholder of path.matchAll(/\{([^{}]+)\}/g)) {
        const arg = args.find(a => a.param?.in === "path" && a.param.name === placeholder[1]);
        if (!arg) throw new Error(`${op.operationId}: undeclared path parameter ${placeholder[1]}`);
        pathExpr += `.replace(${q(placeholder[0])}, Wire.encode(Wire.scalar(${arg.shape.codec}.write(${id(arg.name)}))))`;
      }
      for (const arg of args.filter(a => a.param?.in === "path")) if (!path.includes(`{${arg.param!.name}}`)) throw new Error(`${op.operationId}: unused path parameter`);
      function pairs(location: string): string {
        return args.filter(a => a.param?.in === location).map(a => {
          const param = a.param!;
          const explode = param.explode ?? ["query", "cookie"].includes(location);
          const encode = (value: string) => `Wire.parameters(${q(param.name)}, ${a.shape.codec}.write(${value}), ${explode})`;
          return a.required ? encode(id(a.name)) : `${id(a.name)}.toOption.toVector.flatMap(value => ${encode("value")})`;
        }).join(" ++ ") || "Vector.empty";
      }
      const headers = `${pairs("header")} ++ ${body ? 'Vector("Content-Type" -> "application/json")' : "Vector.empty"} ++ { val cookies: Vector[(String, String)] = ${pairs("cookie")}; if cookies.isEmpty then Vector.empty else Vector("Cookie" -> cookies.map((k, v) => Wire.encode(k) + "=" + Wire.encode(v)).mkString("; ")) }`;
      const payload = !body ? "None" : body.required ? `Some(${body.shape.codec}.write(${id(body.name)}).noSpaces)` : `${id(body.name)}.toOption.map(value => ${body.shape.codec}.write(value).noSpaces)`;
      const variants: { status: number; media?: string; shape: Shape; decode: string; name: string }[] = [];
      for (const [status, rawResponse] of Object.entries(object(op.responses, `${op.operationId}.responses`)).sort()) {
        if (!/^2/.test(status)) continue;
        if (!/^2\d\d$/.test(status)) throw new Error(`${op.operationId}: success status ranges are unsupported`);
        const response = resolve(rawResponse);
        const content = method === "head" ? [] : Object.entries(response.content ?? {});
        if (!content.length) variants.push({ status: Number(status), shape: { type: "Unit", codec: "" }, decode: "Right(())", name: `Status${status}` });
        for (const [media, rawContent] of content) {
          if (media !== "text/plain" && media !== "application/json" && !media.endsWith("+json")) throw new Error(`${op.operationId}: unsupported response media ${media}`);
          const s = media === "text/plain" ? { type: "String", codec: "JsonCodec.string" } : shape(object(rawContent, media).schema ?? {}, `${prefix}Response${status}`);
          variants.push({ status: Number(status), media, shape: s, decode: media === "text/plain" ? "Right(response.body)" : `Wire.json(response, ${s.codec})`, name: `Status${status}${typeName(media)}` });
        }
      }
      if (!variants.length) throw new Error(`${op.operationId}: no declared success response`);
      const result = variants.length === 1 ? variants[0]!.shape.type : reserve(`${prefix}Result`);
      if (variants.length > 1) definitions.push(`enum ${result}:\n${variants.map(v => `  case ${v.name}(value: ${v.shape.type})`).join("\n")}`);
      const branches = variants.map(v => `case ${v.status}${v.media ? ` if response.mediaType.contains(${q(v.media)})` : ""} => ${v.decode}${variants.length > 1 ? `.map(${result}.${v.name}.apply)` : ""}`).join("\n");
      operations.push({
        segments: op.operationId.split("."),
        signature: args.map(a => `${id(a.name)}: ${a.required ? a.shape.type : `Optional[${a.shape.type}] = Optional.Missing`}`).join(", "),
        args: args.map(a => id(a.name)).join(", "), result,
        expression: `Call[${result}](\n  HttpRequest(${q(method.toUpperCase())}, ${pathExpr}, query = ${pairs("query")}, headers = ${headers}, body = ${payload}),\n  response => response.status match\n${branches.split("\n").map(l => `    ${l}`).join("\n")}\n    case _ => Wire.unexpected(response)\n)`,
        description: op.description ?? op.summary ?? "",
      });
    }
  }
  operations.sort((a, b) => a.segments.join(".").localeCompare(b.segments.join("."), "en"));
  interface Node { children: Map<string, Node>; operation?: Operation }
  const root: Node = { children: new Map() };
  for (const op of operations) {
    let node = root;
    for (const segment of op.segments) {
      if (node.operation) throw new Error(`Command is also a namespace: ${op.segments.join(".")}`);
      if (!node.children.has(segment)) node.children.set(segment, { children: new Map() });
      node = node.children.get(segment)!;
    }
    if (node.children.size) throw new Error(`Command is also a namespace: ${op.segments.join(".")}`);
    node.operation = op;
  }
  function render(node: Node, bound: boolean, depth = 1): string {
    const pad = "  ".repeat(depth);
    return [...node.children].map(([name, child]) => {
      if (!child.operation) return `${pad}object ${id(name)}:\n${render(child, bound, depth + 1)}`;
      const op = child.operation;
      const comment = op.description ? `${pad}/** ${String(op.description).replace(/\*\//g, "* /").replace(/[\r\n]/g, " ")} */\n` : "";
      const expression = bound ? `executor.execute(Calls.${op.segments.map(id).join(".")}(${op.args}))` : op.expression;
      return `${comment}${pad}def ${id(name)}(${op.signature}): ${bound ? "F" : "Call"}[${op.result}] =\n${expression.split("\n").map(line => `${pad}  ${line}`).join("\n")}`;
    }).join("\n\n");
  }
  const prelude = `${header}package ${packageName.split(".").map(id).join(".")}\n\nimport sprout.sdk.*\nimport io.circe.Json\n\n`;
  return {
    "Models.scala": prelude + definitions.join("\n\n") + "\n",
    "Calls.scala": prelude + `object Calls:\n${root.children.size ? render(root, false) : "  ()"}\n`,
    "Client.scala": prelude + `final class Client[F[_]](executor: Executor[F]):\n${root.children.size ? render(root, true) : "  ()"}\n`,
  };
}

export const generatedHeader = header;
